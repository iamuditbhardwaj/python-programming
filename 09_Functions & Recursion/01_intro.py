# Functions

# Functions in Python are a call-able piece of code which can be used as many number of times in a single program
# Syntax:
'''def function_name():
    // statement'''     # This is function definition    

'''function_name()'''   # This is a function call

# There are two types of function in python
# 1. Build in function (Already present in python)
# 2. User defined function (Defined by the user in program)

# Example
def fun():
    print("This is a function !!!!")

fun()
